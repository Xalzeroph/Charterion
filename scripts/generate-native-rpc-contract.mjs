import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const manifestPath = resolve(root, 'shared/native-rpc-protocol.json');
const tsPath = resolve(root, 'src/nativeRpcProtocol.generated.ts');
const csPath = resolve(root, 'native-host/GamNativeHost/NativeRpcProtocol.g.cs');
const psPath = resolve(root, 'native-host/scripts/NativeRpcProtocol.generated.ps1');
const check = process.argv.includes('--check');

function fail(message) {
  throw new Error(`NATIVE_RPC_CONTRACT_ERROR ${message}`);
}

function validateManifest(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) fail('manifest must be an object');
  if (value.schemaVersion !== 1) fail('schemaVersion must be 1');
  if (typeof value.host !== 'string' || !/^[a-z0-9]+(?:[._-][a-z0-9]+)+$/i.test(value.host)) fail('host is invalid');
  if (!Number.isInteger(value.maxMessageBytes) || value.maxMessageBytes < 1024 || value.maxMessageBytes > 64 * 1024 * 1024) fail('maxMessageBytes is invalid');
  if (!Array.isArray(value.methods) || value.methods.length === 0) fail('methods must be a non-empty array');
  const seen = new Set();
  for (const [index, method] of value.methods.entries()) {
    if (!method || typeof method !== 'object' || Array.isArray(method)) fail(`methods[${index}] must be an object`);
    if (typeof method.name !== 'string' || !/^[a-z][a-z0-9.-]*$/i.test(method.name)) fail(`methods[${index}].name is invalid`);
    if (seen.has(method.name)) fail(`duplicate method ${method.name}`);
    seen.add(method.name);
    if (typeof method.domain !== 'string' || !/^[a-z][a-z0-9-]*$/i.test(method.domain)) fail(`methods[${index}].domain is invalid`);
  }
  return value;
}

function quoteTs(value) {
  return JSON.stringify(value);
}

function quoteCs(value) {
  return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

function quotePs(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function renderTs(manifest) {
  const methods = manifest.methods.map((method) => `  ${quoteTs(method.name)},`).join('\n');
  const domains = [...new Set(manifest.methods.map((method) => method.domain))].sort().map((domain) => `  ${quoteTs(domain)},`).join('\n');
  const domainEntries = manifest.methods.map((method) => `  ${quoteTs(method.name)}: ${quoteTs(method.domain)},`).join('\n');
  return `// GENERATED FILE. Source: shared/native-rpc-protocol.json\n// Run: npm run generate:native-rpc-contract\n\nexport const NATIVE_CONTROL_HOST = ${quoteTs(manifest.host)} as const;\nexport const NATIVE_MAX_MESSAGE_BYTES = ${manifest.maxMessageBytes} as const;\n\nexport const NATIVE_RPC_METHODS = [\n${methods}\n] as const;\n\nexport type NativeRpcMethod = typeof NATIVE_RPC_METHODS[number];\n\nexport const NATIVE_RPC_DOMAINS = [\n${domains}\n] as const;\n\nexport type NativeRpcDomain = typeof NATIVE_RPC_DOMAINS[number];\n\nexport const NATIVE_RPC_METHOD_DOMAIN: Readonly<Record<NativeRpcMethod, NativeRpcDomain>> = {\n${domainEntries}\n};\n\nconst nativeRpcMethodSet: ReadonlySet<string> = new Set(NATIVE_RPC_METHODS);\n\nexport function assertNativeRpcMethod(method: string): asserts method is NativeRpcMethod {\n  if (!nativeRpcMethodSet.has(method)) throw new Error(\`Native RPC method \${method} is not declared in shared/native-rpc-protocol.json\`);\n}\n`;
}

function renderCs(manifest) {
  const methods = manifest.methods.map((method) => `        ${quoteCs(method.name)},`).join('\n');
  return `// <auto-generated />\n// Source: shared/native-rpc-protocol.json\nusing System;\nusing System.Collections.Generic;\n\ninternal static class NativeRpcProtocol\n{\n    public const string Host = ${quoteCs(manifest.host)};\n    public const int MaxMessageBytes = ${manifest.maxMessageBytes};\n    public static readonly HashSet<string> AllowedMethods = new(StringComparer.Ordinal)\n    {\n${methods}\n    };\n}\n`;
}

function renderPs(manifest) {
  return `# GENERATED FILE. Source: shared/native-rpc-protocol.json\n# Run: npm run generate:native-rpc-contract\n$script:CharterionNativeHostName = ${quotePs(manifest.host)}\n$script:CharterionNativeMaxMessageBytes = ${manifest.maxMessageBytes}\n`;
}

async function compareOrWrite(path, expected) {
  if (check) {
    let actual = '';
    try { actual = await readFile(path, 'utf8'); } catch { fail(`${path} is missing; run npm run generate:native-rpc-contract`); }
    if (actual.replaceAll('\r\n', '\n') !== expected.replaceAll('\r\n', '\n')) {
      fail(`${path} is stale; run npm run generate:native-rpc-contract and commit the generated output`);
    }
    return;
  }
  const normalized = expected.replaceAll('\r\n', '\n');
  let actual = '';
  try { actual = await readFile(path, 'utf8'); } catch { /* create below */ }
  if (actual.replaceAll('\r\n', '\n') === normalized) return;
  await writeFile(path, normalized, 'utf8');
}

const manifest = validateManifest(JSON.parse(await readFile(manifestPath, 'utf8')));
await Promise.all([
  compareOrWrite(tsPath, renderTs(manifest)),
  compareOrWrite(csPath, renderCs(manifest)),
  compareOrWrite(psPath, renderPs(manifest)),
]);

console.log(check
  ? `NATIVE_RPC_CONTRACT_CHECK_PASS methods=${manifest.methods.length}`
  : `NATIVE_RPC_CONTRACT_GENERATED methods=${manifest.methods.length}`);
